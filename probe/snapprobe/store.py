    # Dove si trovava l'archivio prima del passaggio a PostgreSQL. Si guarda solo
    # all'avvio, e solo se il nuovo archivio e' vuoto.
    PERCORSI_SQLITE = ("/data/snap_probe.sqlite3", "data/snap_probe.sqlite3")

    def importa_da_sqlite(self, percorso: str = None) -> dict:
        """Copia nel nuovo archivio i dati di quello SQLite, se ce n'e' uno.

        PERCHE' ESISTE
        Un porting che perde i dati non e' un porting, e' un azzeramento. Nel file
        SQLite di una sonda in esercizio ci sono tre cose che non si possono
        rifare da zero senza intervento umano:

          * la REGISTRAZIONE (probe_uid, chiave di sessione, chiave API): senza,
            la sonda non e' piu' riconosciuta dal server e va registrata di nuovo
            a mano, con un pacchetto generato dalla console;
          * la CODA di conferimento: dati raccolti e non ancora consegnati, che
            sono esattamente cio' che la sonda esiste per non perdere;
          * lo stato dei nodi e delle fasi: senza, tutto il lavoro di scansione
            ricomincia da capo -- su 78.000 indirizzi sono giorni.

        Si importa UNA volta sola e solo se il nuovo archivio e' VUOTO: un secondo
        passaggio sovrascriverebbe dati piu' recenti con dati piu' vecchi. Alla fine
        il file viene rinominato, cosi' resta come copia ma non viene piu' guardato.

        Restituisce quante righe sono state importate per tabella.
        """
        import logging
        import os
        import sqlite3

        diario = logging.getLogger("snapprobe")
        candidati = [percorso] if percorso else list(self.PERCORSI_SQLITE)
        origine = next((c for c in candidati if c and os.path.isfile(c)), None)
        if origine is None:
            return {}

        # SOLO SU UN ARCHIVIO NON ANCORA IN USO, e il criterio va scelto bene: la
        # prima versione contava le righe di `settings`, ma un archivio appena creato
        # ne ha comunque qualcuna (le scrive l'avvio), quindi l'importazione non
        # partiva mai. Cio' che distingue "vuoto" da "in uso" e' la REGISTRAZIONE --
        # senza quella la sonda non ha mai parlato con un server -- piu' l'assenza di
        # nodi propri.
        with self._lock, self._connect() as connessione:
            riga = connessione.execute(
                "SELECT (SELECT COUNT(*) FROM local_nodes) AS nodi,"
                " (SELECT COUNT(*) FROM settings WHERE key = 'probe_uid') AS registrata"
            ).fetchone()
        # Il criterio e' la SOLA registrazione, e la ragione e' costata un tentativo:
        # contando anche i nodi, un'importazione interrotta a meta' (i nodi copiati,
        # le impostazioni no) risultava "in uso" al riavvio successivo e non
        # riprendeva -- lasciando la sonda senza registrazione, cioe' muta. Una volta
        # che la sonda e' registrata, invece, l'archivio e' suo e non si tocca.
        gia_in_uso = int(riga["registrata"]) > 0
        if gia_in_uso:
            diario.info("Archivio SQLite presente (%s) ma il nuovo archivio e' gia'"
                        " in uso: non si importa nulla", origine)
            return {}

        vecchio = sqlite3.connect("file:%s?mode=ro" % origine, uri=True)
        vecchio.row_factory = sqlite3.Row
        importate = {}
        try:
            tabelle = {r[0] for r in vecchio.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table'")}
            for tabella in tuple(self.DATA_TABLES) + ("settings",):
                if tabella not in tabelle:
                    continue
                righe_vecchie = vecchio.execute(
                    "SELECT * FROM %s" % tabella).fetchall()
                if not righe_vecchie:
                    continue
                colonne = list(righe_vecchie[0].keys())
                # `id` non si copia: le tabelle con chiave generata la rigenerano, e
                # portarsi dietro i vecchi valori significherebbe scontrarsi con la
                # sequenza.
                colonne = [c for c in colonne if c != "id"]
                elenco = ",".join('"%s"' % nome_sicuro(c) for c in colonne)
                segnaposto = ",".join("?" for _ in colonne)
                # RIPETIBILE PER COSTRUZIONE. Le impostazioni si sovrascrivono --
                # quelle dell'archivio precedente sono le vere, e le poche scritte
                # dall'avvio sono valori predefiniti -- il resto si salta se c'e'
                # gia'. Senza questo, una sola collisione interrompeva l'intera
                # importazione a metà: e' quello che e' successo.
                if tabella == "settings":
                    coda_conflitto = (" ON CONFLICT (key) DO UPDATE SET"
                                      " value = excluded.value,"
                                      " updated_at = excluded.updated_at")
                else:
                    coda_conflitto = " ON CONFLICT DO NOTHING"
                with self._lock, self._connect() as connessione:
                    connessione.executemany(
                        "INSERT INTO %s (%s) VALUES (%s)%s"
                        % (nome_sicuro(tabella), elenco, segnaposto, coda_conflitto),
                        [tuple(r[c] for c in colonne) for r in righe_vecchie])
                importate[tabella] = len(righe_vecchie)
        finally:
            vecchio.close()

        # Il file resta come copia, con un nome che dice che e' stato importato: non
        # si cancella un archivio di dati altrui, e non si rischia una seconda
        # importazione.
        try:
            os.rename(origine, origine + ".importato")
        except OSError as errore:
            # Non e' fatale -- l'importazione e' avvenuta -- ma va detto, perche' se
            # il file resta e il nuovo archivio venisse svuotato si riimporterebbe.
            diario.warning("Archivio SQLite importato ma non rinominato (%s): %s",
                           origine, errore)
        totale = sum(importate.values())
        if totale:
            self.log("warning",
                     "Importate %d righe dall'archivio SQLite precedente (%s)"
                     % (totale, ", ".join("%s:%d" % (t, n)
                                          for t, n in sorted(importate.items()))))
            diario.warning("Importazione da SQLite completata: %d righe", totale)
        return importate

