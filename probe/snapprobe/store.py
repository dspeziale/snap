    def ids_confronta(self, genere: str, soggetto: str, valore: str,
                      adesso) -> dict:
        """Confronta un valore osservato con cio' che era normale, e aggiorna.

        Restituisce sempre un esito con tre bandiere, perche' chi chiama deve poter
        distinguere tre situazioni che un semplice "e' cambiato" confonderebbe:

        * `nuovo`   -- di questo soggetto non si sapeva nulla: non e' un cambiamento,
                       e' una prima volta;
        * `cambiato`-- il valore e' diverso da quello noto;
        * `maturo`  -- la memoria del soggetto e' piu' vecchia di MATURITA_ORE, quindi
                       il cambiamento vale come rilevazione. Sotto quella soglia si
                       registra e basta: non si puo' dire "e' cambiato" di qualcosa
                       visto una volta sola.

        La memoria si aggiorna SEMPRE: una rilevazione non deve ripetersi a ogni giro.
        """
        from .ids import MATURITA_ORE

        istante = adesso.strftime(UTC_FORMAT) if hasattr(adesso, "strftime") else str(adesso)
        with self._connect() as connection:
            riga = connection.execute(
                "SELECT valore, visto_da, visto_a, conferme FROM local_ids_baseline"
                " WHERE genere = ? AND soggetto = ?", (genere, soggetto)).fetchone()
            if riga is None:
                connection.execute(
                    "INSERT INTO local_ids_baseline (genere, soggetto, valore, visto_da,"
                    " visto_a, conferme) VALUES (?, ?, ?, ?, ?, 1)",
                    (genere, soggetto, valore, istante, istante))
                return {"nuovo": True, "cambiato": False, "maturo": False,
                        "prima": None, "visto_da": istante}

            prima = riga["valore"]
            cambiato = prima != valore
            eta = _differenza_ore(riga["visto_da"], istante)
            maturo = cambiato and eta >= MATURITA_ORE
            connection.execute(
                "UPDATE local_ids_baseline SET valore = ?, visto_a = ?,"
                " conferme = conferme + 1 WHERE genere = ? AND soggetto = ?",
                (valore, istante, genere, soggetto))
            return {"nuovo": False, "cambiato": cambiato, "maturo": maturo,
                    "prima": prima, "visto_da": riga["visto_da"]}

    def ids_memoria_matura(self) -> dict:
        """Da quanto esiste la memoria di cio' che e' normale.

        Serve a una regola sola ma decisiva: **finche' l'archivio e' giovane, il
        motore impara e non giudica.** La maturita' del singolo soggetto non basta --
        un soggetto appena visto non ha memoria per definizione, e con quella sola
        condizione la prima passata segnala l'intera rete come "mai vista". E'
        successo: quattrocento rilevazioni al primo giro, che e' il modo piu' rapido
        per far disattivare un IDS.
        """
        from .ids import MATURITA_ORE

        with self._connect() as connection:
            riga = connection.execute(
                "SELECT MIN(visto_da) AS dal, COUNT(*) AS soggetti FROM local_ids_baseline"
            ).fetchone()
        dal = (riga or {})["dal"]
        soggetti = int((riga or {})["soggetti"] or 0)
        if not dal or not soggetti:
            return {"matura": False, "dal": None, "ore": 0.0, "soggetti": 0}
        ore = _differenza_ore(dal, utc_now_str())
        return {"matura": ore >= MATURITA_ORE, "dal": dal, "ore": round(ore, 1),
                "soggetti": soggetti}

    def ids_registra(self, regola: str, gravita: str, sensore: str, soggetto: str,
                     titolo: str, prova: str, tecnica: str, dati: dict,
                     adesso: str) -> str:
        """Registra una rilevazione. La stessa, sullo stesso soggetto, si AGGIORNA.

        Mille volte lo stesso fatto e' un fatto che dura, non mille fatti: duplicare
        riempirebbe la pagina e farebbe perdere quello nuovo in mezzo ai vecchi.
        """
        with self._connect() as connection:
            esistente = connection.execute(
                "SELECT id FROM local_ids_findings WHERE regola = ? AND soggetto = ?",
                (regola, soggetto)).fetchone()
            if esistente is not None:
                connection.execute(
                    "UPDATE local_ids_findings SET conteggio = conteggio + 1, ultima_at = ?,"
                    " prova = ?, dati_json = ?, conferita_at = NULL WHERE id = ?",
                    (adesso, prova[:2000],
                     json.dumps(dati, separators=(",", ":"), default=str),
                     esistente["id"]))
                return "aggiornata"
            connection.execute(
                "INSERT INTO local_ids_findings (regola, gravita, sensore, soggetto, titolo,"
                " prova, tecnica, dati_json, conteggio, prima_at, ultima_at)"
                " VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?)",
                (regola, gravita, sensore, soggetto, titolo[:500], prova[:2000],
                 tecnica or None,
                 json.dumps(dati, separators=(",", ":"), default=str), adesso, adesso))
            return "nuova"

