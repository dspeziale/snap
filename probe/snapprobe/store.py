def utc_now_str() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).strftime(UTC_FORMAT)


def days_ago_str(days: int) -> str:
    moment = datetime.now(timezone.utc) - timedelta(days=days)
    return moment.strftime(UTC_FORMAT)


class _Transazione:
    """Gestore di contesto che apre una transazione e la conferma uscendo.

    Riproduce il contratto di `sqlite3.connect(...)` usata come `with`: e' il modo in
    cui i sessanta punti di SQL di questo modulo sono scritti, e conservarlo e' cio'
    che ha permesso di cambiare archivio senza riscriverli.
    """

    __slots__ = ("_motore", "_contesto", "_connessione")

    def __init__(self, motore_dati):
        self._motore = motore_dati
        self._contesto = None
        self._connessione = None

    def __enter__(self) -> Connessione:
        self._contesto = self._motore.begin()
        self._connessione = self._contesto.__enter__()
        return Connessione(self._connessione)

    def __exit__(self, tipo, valore, traccia):
        return self._contesto.__exit__(tipo, valore, traccia)


class ProbeStore:
    """Archivio locale della sonda, su PostgreSQL.

    IL LUCCHETTO C'E' ANCORA, e va spiegato perche' con PostgreSQL non servirebbe:
    la serializzazione era necessaria a SQLite (un file, scritture che si escludono).
    Qui la manteniamo per fare UNA modifica per volta -- il comportamento resta
    identico a quello verificato -- e perche' e' la rete di sicurezza della
    prenotazione atomica dei bersagli. Togliendolo il pool servirebbe i trentadue
    thread davvero in parallelo: e' il passo successivo, da fare misurando, non
    insieme al cambio di archivio.

    `path` resta nella firma per compatibilita' con chi la costruisce (l'interfaccia
    locale, i test): non e' piu' un file, e non si usa. La connessione viene dal
    motore, che legge SNAP_PROBE_DATABASE_URL.
    """

    # Quanto si attende l'archivio all'avvio, e ogni quanto si riprova. La sonda e'
    # un apparato lasciato in sede: deve avviarsi anche se la propria base dati parte
    # con qualche secondo di ritardo, e non puo' dipendere dall'ordine dei
    # contenitori -- nella variante per Docker Desktop la base dati usa la RETE della
    # sonda, quindi la sonda deve partire per prima. Attendere qui e' l'unico modo.
    ATTESA_ARCHIVIO_SEC = 90
    ATTESA_FRA_TENTATIVI_SEC = 2.0

    def __init__(self, path: str = None):
        self.path = path
        # IL LUCCHETTO SERVE A UNA COSA SOLA, e va detto perche' prima ne proteggeva
        # quarantatre e non doveva.
        #
        # Con SQLite un solo scrittore per volta era un obbligo del formato: un
        # lucchetto globale sull'archivio era la scelta giusta. Con PostgreSQL non lo
        # e' piu' -- ogni operazione apre la PROPRIA transazione dal pool (vedi
        # `_connect`), e il database gestisce la concorrenza. Il lucchetto era
        # sopravvissuto al porting, e metteva in fila i trentadue thread di
        # scansione, l'agente, i controlli e l'interfaccia web: uno per volta.
        #
        # MISURATO su questa installazione, ed e' il motivo per cui e' stato tolto:
        # con il lucchetto la pagina di accesso della sonda impiegava cinque secondi
        # e andava in timeout oltre i quindici, mentre la base dati aveva DUE query
        # attive su un limite di cento connessioni e la CPU stava al 42% di un solo
        # nucleo su dodici. Non era carico: era una coda.
        #
        # Resta qui perche' `importa_da_sqlite` -- l'importazione una tantum del
        # vecchio archivio -- fa una lettura e poi una scrittura in DUE transazioni
        # distinte, e quella sequenza va protetta davvero.
        self._lock = threading.Lock()
        self._attendi_archivio()
        # LO SCHEMA LO CREA IL PROPRIETARIO, i dati li scrive l'applicativo: l'utenza
        # con cui la sonda lavora non puo' cambiare la struttura, quindi non puo'
        # cancellare una tabella per un difetto del programma (minimo privilegio,
        # come sul server). Dove le due utenze coincidono -- sviluppo, test -- questo
        # passaggio e' identico a prima.
        proprietario = motore_proprietario()
        try:
            with proprietario.begin() as connessione:
                grezza = Connessione(connessione)
                # UN LUCCHETTO PRIMA DELLO SCHEMA.
                #
                # `CREATE TABLE IF NOT EXISTS` non e' atomico rispetto al catalogo di
                # PostgreSQL: due processi che lo eseguono insieme si scontrano con
                # "duplicate key value violates unique constraint
                # pg_type_typname_nsp_index", e uno dei due muore all'avvio. Da quando
                # la sonda gira in due processi -- agente e interfaccia -- succede a
                # ogni avvio in cui manchi anche una sola tabella nuova: e' successo.
                #
                # Il lucchetto consultivo di PostgreSQL mette in fila i due: il primo
                # crea, il secondo aspetta e trova tutto fatto. Si libera da se' alla
                # chiusura della connessione, quindi un processo che muore a meta' non
                # lascia l'archivio bloccato.
                connessione.exec_driver_sql(
                    "SELECT pg_advisory_xact_lock(%s)", (_LUCCHETTO_SCHEMA,))
                # Prima dello schema, non dopo: se le tabelle vecchie non vengono
                # rinominate adesso, `CREATE TABLE IF NOT EXISTS` ne crea di nuove e
                # vuote accanto a quelle piene, e i dati restano in quelle che
                # nessuno legge piu'.
                self._rinomina_tabelle_locali(grezza)
                grezza.executescript(SCHEMA)
                self._migrate(grezza)
        finally:
            proprietario.dispose()
        # Se esiste l'archivio SQLite di una versione precedente, i suoi dati si
        # portano qui: registrazione, coda e stato dei nodi. Vedi
        # `importa_da_sqlite` per perche' non si possono perdere.
        self.importa_da_sqlite()

    def _attendi_archivio(self) -> None:
        """Attende che l'archivio risponda, e lo dichiara se non risponde.

        Non e' prudenza generica: il contenitore della base dati puo' avviarsi dopo
        quello della sonda, e un errore all'avvio manderebbe la sonda in ciclo di
        riavvio -- su un apparato in sede, senza nessuno che guardi.
        """
        import logging
        import time

        from sqlalchemy.exc import OperationalError

        diario = logging.getLogger("snapprobe")
        scadenza = time.monotonic() + self.ATTESA_ARCHIVIO_SEC
        ultimo = None
        while True:
            try:
                with motore().connect() as connessione:
                    connessione.exec_driver_sql("SELECT 1")
                return
            except OperationalError as errore:
                # IL MOTIVO SI DICE SUBITO, non solo alla fine. La prima versione
                # scriveva "non ancora pronto" e nient'altro: davanti a un archivio
                # irraggiungibile per una ragione precisa -- una porta che accetta e
                # chiude perche' PostgreSQL ascolta altrove -- quel messaggio manda a
                # cercare nel posto sbagliato. Il primo tentativo porta la causa, i
                # successivi solo il conteggio, cosi' il diario non si riempie.
                primo = ultimo is None
                ultimo = errore
                if time.monotonic() >= scadenza:
                    break
                if primo:
                    diario.warning(
                        "Archivio non raggiungibile (%s): si riprova per %d s. %s",
                        str(errore).splitlines()[0][:160],
                        self.ATTESA_ARCHIVIO_SEC, self._suggerimento_archivio())
                else:
                    diario.warning("Archivio non ancora pronto: nuovo tentativo fra"
                                   " %.0f s", self.ATTESA_FRA_TENTATIVI_SEC)
                # Il motore va dimenticato: una connessione fallita resta nel pool.
                azzera_motore()
                time.sleep(self.ATTESA_FRA_TENTATIVI_SEC)
        raise RuntimeError(
            "Archivio della sonda non raggiungibile dopo %d secondi: %s. %s"
            % (self.ATTESA_ARCHIVIO_SEC, str(ultimo).splitlines()[0][:200],
               self._suggerimento_archivio()))

