            # tengono sette giorni per poter guardare una macchina dalla sonda anche
            # quando il collegamento con la sede e' interrotto.
            connection.execute(
                "DELETE FROM local_agent_metrics WHERE rilevato_at < ? AND conferita_at IS NOT NULL",
                (days_ago_str(7),))

