    def agent_metriche_scrivi(self, agent_uid: str, rilevato_at: str,
                              misure: dict) -> None:
        with self._connect() as connection:
            connection.execute(
                "INSERT INTO local_agent_metrics (agent_uid, rilevato_at, cpu, memoria,"
                " disco_max, processi, in_ascolto, utenti, dati_json)"
                " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (agent_uid, rilevato_at,
                 _numero(misure.get("cpu")), _numero(misure.get("memoria")),
                 _numero(misure.get("disco_max")),
                 _intero(misure.get("processi_totali")),
                 _intero(misure.get("ascolto_totale")),
                 _intero(misure.get("utenti_totali")),
                 json.dumps(misure, separators=(",", ":"), default=str)))
            # La versione dell'agente si aggiorna a ogni invio, non solo alla
            # registrazione: una macchina aggiornata continuava a risultare alla
            # versione con cui era stata registrata mesi prima, e la console mostrava
            # un numero che non esisteva piu' su quella macchina.
            connection.execute(
                "UPDATE local_agents SET ultimo_invio = ?, invii = invii + 1,"
                " versione = COALESCE(?, versione) WHERE agent_uid = ?",
                (rilevato_at, (misure.get("agente") or None), agent_uid))
