    def _rinomina_tabelle_locali(self, connection) -> None:
        """Porta al nome nuovo le tabelle di un archivio gia' in esercizio.

        Si rinomina solo se la vecchia c'e', la nuova no, e la vecchia **e' davvero
        nostra**. L'ultima condizione non e' prudenza generica: nei test la sonda e il
        server condividono un database, e li' esiste un `agent_metrics` che e' del
        SERVER, con altre colonne. Rinominarlo significherebbe portarsi via la tabella
        di un altro applicativo -- ed e' quello che questa migrazione ha fatto al primo
        tentativo, con un errore che non somigliava per niente alla sua causa.

        Il segno di riconoscimento e' `tenant_id`: le tabelle del server ce l'hanno
        tutte, perche' il server serve piu' clienti; quelle della sonda non ce l'hanno
        mai, perche' una sonda sta in una rete sola.
        """
        presenti = {riga["table_name"] for riga in connection.execute(
            "SELECT table_name FROM information_schema.tables"
            " WHERE table_schema = current_schema()").fetchall()}
        for vecchia, nuova in self.RINOMINATE:
            if vecchia not in presenti or nuova in presenti:
                continue
            colonne = {riga["column_name"] for riga in connection.execute(
                "SELECT column_name FROM information_schema.columns"
                " WHERE table_schema = current_schema() AND table_name = ?",
                (vecchia,)).fetchall()}
            if "tenant_id" in colonne:
                continue  # e' del server: non si tocca
            connection.execute('ALTER TABLE "%s" RENAME TO "%s"'
                               % (nome_sicuro(vecchia), nome_sicuro(nuova)))
            for indice in self.INDICI_SUPERATI.get(vecchia, ()):
                connection.execute('DROP INDEX IF EXISTS "%s"' % nome_sicuro(indice))

    def _migrate(self, connection) -> None:
        """Aggiunge le colonne introdotte dopo la prima installazione.

        Il catalogo si interroga con `information_schema`, che e' lo standard, invece
        che con i PRAGMA di SQLite.
        """
        for tabella, colonna, tipo in self.MIGRATIONS:
            presente = connection.execute(
                "SELECT 1 FROM information_schema.tables"
                " WHERE table_schema = current_schema() AND table_name = ?",
                (tabella,),
            ).fetchone()
            if presente is None:
                continue  # la tabella nasce dallo schema, con la colonna inclusa
            colonne = {riga["column_name"] for riga in connection.execute(
                "SELECT column_name FROM information_schema.columns"
                " WHERE table_schema = current_schema() AND table_name = ?",
                (tabella,)).fetchall()}
            if colonna not in colonne:
                # Nome e tipo vengono da MIGRATIONS, non dall'esterno; si ripuliscono
                # comunque, perche' nessuna distrazione futura possa farne un varco.
                connection.execute('ALTER TABLE "%s" ADD COLUMN "%s" %s'
                                   % (nome_sicuro(tabella), nome_sicuro(colonna), tipo))

