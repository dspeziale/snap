    def agenti_da_conferire(self, limite: int = 200) -> list:
        """Le macchine mai conferite, o il cui stato e' cambiato da allora.

        Tre condizioni, e servono tutte e tre:

        * `conferita_at IS NULL` -- mai conferita. Senza questa, una macchina appena
          registrata e non ancora avviata avrebbe `ultimo_invio` e `conferito_invio`
          entrambi nulli, quindi non "diversi", e non sarebbe arrivata mai: sulla
          pagina della sonda si vedeva, su quella della console no.
        * l'ultimo invio e' cambiato -- ha mandato qualcosa di nuovo;
        * l'inventario e' cambiato -- e' la parte pesante, e va solo quando serve.

        `IS DISTINCT FROM` e non `<>`: con il secondo un confronto che tocca un nullo
        non e' ne' vero ne' falso, e la riga sparirebbe dal risultato.
        """
        with self._connect() as connection:
            righe = connection.execute(
                "SELECT * FROM local_agents"
                " WHERE conferita_at IS NULL"
                "    OR ultimo_invio IS DISTINCT FROM conferito_invio"
                "    OR inventario_at IS DISTINCT FROM inventario_conferito_at"
                " ORDER BY ultimo_invio DESC NULLS LAST LIMIT ?",
                (int(limite),)).fetchall()
        return [dict(r) for r in righe]

