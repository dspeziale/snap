def _differenza_ore(prima: str, dopo: str) -> float:
    """Ore fra due istanti dell'archivio. Un valore illeggibile vale zero: meglio
    non allarmare che allarmare su una data che non si sa leggere."""
    try:
        a = datetime.strptime(str(prima), UTC_FORMAT)
        b = datetime.strptime(str(dopo), UTC_FORMAT)
    except (TypeError, ValueError):
        return 0.0
    return (b - a).total_seconds() / 3600.0


