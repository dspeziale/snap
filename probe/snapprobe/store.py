    def agent_segna_conferiti(self, tabella: str, identificativi: list,
                              adesso: str) -> None:
        if not identificativi:
            return
        # Allowlist: il nome della tabella non arriva mai dall'esterno, ma scriverlo
        # in chiaro nella query lo rende verificabile a colpo d'occhio.
        colonna = {"local_agent_metrics": "conferita_at", "local_agent_events": "conferito_at"}
        if tabella not in colonna:
            raise ValueError("tabella non prevista: %r" % tabella)
        segnaposti = ", ".join("?" for _ in identificativi)
        with self._connect() as connection:
            connection.execute(
                "UPDATE %s SET %s = ? WHERE id IN (%s)"
                % (tabella, colonna[tabella], segnaposti),
                tuple([adesso] + [int(i) for i in identificativi]))

    def agent_metriche_recenti(self, agent_uid: str, limite: int = 120) -> list:
        with self._connect() as connection:
            righe = connection.execute(
                "SELECT * FROM local_agent_metrics WHERE agent_uid = ?"
                " ORDER BY rilevato_at DESC LIMIT ?",
                (agent_uid, int(limite))).fetchall()
        return [dict(r) for r in righe]

    def agent_eventi_recenti(self, agent_uid: str = None, limite: int = 100) -> list:
        with self._connect() as connection:
            if agent_uid:
                righe = connection.execute(
                    "SELECT * FROM local_agent_events WHERE agent_uid = ?"
                    " ORDER BY id DESC LIMIT ?", (agent_uid, int(limite))).fetchall()
            else:
                righe = connection.execute(
                    "SELECT * FROM local_agent_events ORDER BY id DESC LIMIT ?",
                    (int(limite),)).fetchall()
        return [dict(r) for r in righe]
